  /// Only devices without ISRG Root X1 (before Android 7.1.1). On newer ones the
  /// roots are already there, and adding one twice throws
  /// CERT_ALREADY_IN_HASH_TABLE.
  static bool neededOn(int sdk) => sdk > 0 && sdk < 25;

  /// SHA-256 of [pem]'s certificate (DER), to check a copy is the real one.
  static String sha256Of(String pem) {
    final body = pem
        .replaceAll('-----BEGIN CERTIFICATE-----', '')
        .replaceAll('-----END CERTIFICATE-----', '')
        .replaceAll(RegExp(r'\s'), '');
    return sha256.convert(base64.decode(body)).toString();
  }

  /// Adds the roots to [context]; returns the ones it took.
  static List<String> addTo(SecurityContext context) {
    final added = <String>[];
    for (final e in certificates.entries) {
      try {
        context.setTrustedCertificatesBytes(utf8.encode(e.value));
        added.add(e.key);
      } on TlsException catch (err) {
        debugPrint('ExtraRootCerts: ${e.key} not added: $err');
      }
    }
    return added;
  }

  /// At startup, before any HTTPS request (Android only).
  static Future<void> installIfNeeded() async {
    if (!Platform.isAndroid) return;
    final sdk = await DeviceTypeService.sdkInt();
    if (!neededOn(sdk)) return;
    final added = addTo(SecurityContext.defaultContext);
    debugPrint('ExtraRootCerts: Android SDK $sdk, now trusting '
        '${added.isEmpty ? 'nothing' : added.join(' + ')} (Let\'s Encrypt)');
  }
